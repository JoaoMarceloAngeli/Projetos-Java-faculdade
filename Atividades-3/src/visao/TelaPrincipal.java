    private void listarClientes(){
    try {
        LinkedList<Professor>[] array = professor.listar();
        jTable_Saida.setRowHeight(100);
        jTable_Saida.setModel(new javax.swing.table.DefaultTableModel(
        new Object [][] {},
        new String [] {"Posicao"}
        ));
        DefaultTableModel model = (DefaultTableModel) jTable_Saida.getModel();
        int tamanh = coliso;
        tamanh++;
        String[] saida = new String[tamanh];
        int profTabela = 0;
        tamanh--;
        for(int i = 0;i < tamanh; i++){
        profTabela = i;
        profTabela++;
        model.addColumn("Professor"+" "+"("+(profTabela)+")");
        }  
        for (int i = 0; i < tamanh+1; i++) {
              jTable_Saida.getColumnModel().getColumn(i).setCellRenderer(new MultiLineTableCellRenderer());
          }
        model.setNumRows(0);
        int size;
        int c = 1;
        size = array.length;
        for(int i = 0;i < size; i++){
            saida[0] = i + "";
            for(int j = 0;j < tamanh; j++){
            if((array[i].get(j)) != null){
            saida[c] = array[i].get(j).toString();
            }
            else{
            saida[c] = "";
            }
            c++;
            }
            model.addRow(saida);
            c = 1;
        }
    } catch (Exception erro) {
        JOptionPane.showMessageDialog(this, erro.getMessage());
    }
}

