    private void jButton_IncluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton_IncluirActionPerformed
        // TODO add your handling code here:
        try {
            if(jTextField_Matricula.getText().isEmpty()) throw new Exception("Esse campo (Matricula) nao pode estar vazio.");
           if(!jTextField_Matricula.getText().matches("[0-9]+")) throw new Exception ("Esse campo (Matricula) somente aceita numeros.");            
           Professor novoProfessor = new Professor(Integer.parseInt(jTextField_Matricula.getText()), jTextField_Nome.getText().toUpperCase(), jTextField_Escola.getText().toUpperCase(), titulacao.valueOf(jComboBox_Titulacao.getSelectedItem().toString()).getDescricao(), contrato.valueOf(jComboBox_Contrato.getSelectedItem().toString()).getDescricao());
            professor.incluir(novoProfessor);
            listarClientes();
            jTextField_Nome.setText("");
            jTextField_Matricula.setText("");
            jTextField_Escola.setText("");

        } catch (Exception erro) {
            JOptionPane.showMessageDialog(this, erro.getMessage() + " Incluir");
        }
    }//GEN-LAST:event_jButton_IncluirActionPerformed

    private void jButton_CarregarArqActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton_CarregarArqActionPerformed
        // TODO add your handling code here:
        JFileChooser fc = new JFileChooser();
        FileNameExtensionFilter filtro = new FileNameExtensionFilter("text","csv");
        fc.setFileFilter(filtro);
        int res = fc.showOpenDialog(null);
        if (res == JFileChooser.APPROVE_OPTION) {
            File arquivo = fc.getSelectedFile();
            ManipArq dados = new ManipArq(arquivo);
            try {
                professor = dados.obterProfess();
                coliso = (dados.obterProfess().getColisoes());
            } catch (Exception e) {
            }
            listarClientes();
            jButton_Incluir.setEnabled(true);
            jTextField_Nome.setEnabled(true);
            jTextField_Matricula.setEnabled(true);
            jTextField_Escola.setEnabled(true);
            jComboBox_Contrato.setEnabled(true);
            jComboBox_Titulacao.setEnabled(true);
        }
    }//GEN-LAST:event_jButton_CarregarArqActionPerformed

