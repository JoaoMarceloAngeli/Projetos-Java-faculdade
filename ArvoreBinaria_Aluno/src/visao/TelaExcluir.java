    private void jButton_OKActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton_OKActionPerformed
        // TODO add your handling code here:
        try{
            if(jTextField_Deletar.getText().isEmpty()) throw new Exception("Campo de Busca Vazio");
            if(jComboBox_Opcoes.getSelectedItem().toString().equals("Matricula")){
                if(!jTextField_Deletar.getText().matches("\\d{4}\\.\\d{1}\\.\\d{3}\\.\\d{4}")) throw new Exception("O Campo de Busca para a matrícula deve ser no formato dddd.d.ddd.dddd (d representa um dígito)");
            }
            arvore = new ArvoreBinaria(jComboBox_Opcoes.getSelectedItem().toString(), ordenarPor);
            for(Aluno aluno : listaDeAlunos){
                arvore.incluir(aluno);
            }
            
            arvore.deletar(jTextField_Deletar.getText());
            
            //System.out.println("-->" + arvore.buscarNaArvore(jTextField_Deletar.getText(), ""));
            
            this.dispose();
        } catch(Exception erro){
            JOptionPane.showMessageDialog(this, "Erro na Janela Excluir: " + erro.getMessage());
        }
    }//GEN-LAST:event_jButton_OKActionPerformed

    
