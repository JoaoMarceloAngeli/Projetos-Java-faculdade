    private void jButton_CarregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton_CarregarActionPerformed
        try{
            JFileChooser fc = new JFileChooser();
            FileNameExtensionFilter filtro = new FileNameExtensionFilter("Texto", "csv");
            fc.setFileFilter(filtro);
            int res = fc.showOpenDialog(null);
            if (res == JFileChooser.APPROVE_OPTION) {
                File arquivoSelecionado = fc.getSelectedFile();
                arquivoAux = arquivoSelecionado;
                ManipulacaoArquivo lerArquivo = new ManipulacaoArquivo(arquivoAux);
                listaDeAlunos = lerArquivo.getDados();
            }
            if(arquivoAux != null){
                jButton_Carregar.setEnabled(false);
                jButton_Incluir.setEnabled(true);
                jButton_Listar.setEnabled(true);
                jButton_Excluir.setEnabled(true);
                jButton_Buscar.setEnabled(true);
                jComboBox_Ordenacao1.setEnabled(true);
                jComboBox_Ordenacao2.setEnabled(true);
            }
        }
        catch(Exception erro){
            JOptionPane.showMessageDialog(this, "Erro ao Carregar: " + erro.getMessage());
        }
    }//GEN-LAST:event_jButton_CarregarActionPerformed

    private void jButton_ListarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton_ListarActionPerformed
         try {
            //if(listaDeAlunos == null) throw new Exception("Lista não Carregada");
            if(arquivoAux == null) throw new Exception("Arquivo não carregado");
            String[] ordenarPor = new String[]{"",""};
            switch(jComboBox_Ordenacao1.getSelectedItem().toString()){
                case "Crescente - Nome":
                    ordenarPor[0] = "Nome";
                    ordenarPor[1] = "Crescente";
                    break;
                case "Decrescente - Nome":
                    ordenarPor[0] = "Nome";
                    ordenarPor[1] = "Decrescente";
                    break;
                case "Crescente - Matricula":
                    ordenarPor[0] = "Matricula";
                    ordenarPor[1] = "Crescente";
                    break;
                case "Decrescente - Matricula":
                    ordenarPor[0] = "Matricula";
                    ordenarPor[1] = "Decrescente";
                    break;
            }
            arvore = new ArvoreBinaria(ordenarPor[0], jComboBox_Ordenacao2.getSelectedItem().toString());
            for(Aluno aluno : listaDeAlunos){
                arvore.incluir(aluno);
            }
            mostrarNaGrid(ordenarPor[1]);
        } catch (Exception erro) {
            JOptionPane.showMessageDialog(this, "Erro ao Listar: " + erro.getMessage());
        }
    }//GEN-LAST:event_jButton_ListarActionPerformed

    
