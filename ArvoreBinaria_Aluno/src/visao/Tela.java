    private void mostrarNaGrid(String opcao){
        try{
            //iArvore arvoreAux = arvore.clonar();
            DefaultTableModel model =  (DefaultTableModel) jTable_Saida.getModel();
            model.setNumRows(0);
            List<Aluno> lista = arvore.getDadosOrdenados(opcao);
            for(Aluno aluno : lista){
                String[] linha = new String[6];
                linha[0] = aluno.getMatricula();
                linha[1] = aluno.getNome();
                linha[2] = aluno.getTurno();
                linha[3] = aluno.getPeriodo()+"";
                linha[4] = aluno.getEnfase();
                linha[5] = aluno.getCurso();
                model.addRow(linha);
            }
        }catch(Exception erro){
            throw erro;
        }
    }
    
