    private void jButton_ExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton_ExcluirActionPerformed
        // TODO add your handling code here:
        try {
            //if(listaDeAlunos == null) throw new Exception("Lista não Carregada");
            if(arquivoAux == null) throw new Exception("Arquivo não carregado");
            
            if(jTable_Saida.isEditing()){
                jTable_Saida.getCellEditor().stopCellEditing();
            }
            jTable_Saida.clearSelection();
            jButton_Excluir.requestFocus();
            
            String ordenacao_Nome_Matricula = (jComboBox_Ordenacao1.getSelectedItem().toString().contains("Nome"))? "Nome":"Matricula";
            TelaExcluir telaExcluir = new TelaExcluir();
            telaExcluir.setLista(listaDeAlunos, jComboBox_Ordenacao2.getSelectedItem().toString());
            telaExcluir.setVisible(true);
            telaExcluir.setDefaultCloseOperation(DISPOSE_ON_CLOSE);
            telaExcluir.addWindowFocusListener(new WindowFocusListener() {
                @Override
                public void windowGainedFocus(WindowEvent e) {
                    if(jTable_Saida.isEditing()){
                        jTable_Saida.getCellEditor().stopCellEditing();
                    }
                    jTable_Saida.clearSelection();
                }

                @Override
                public void windowLostFocus(WindowEvent e) {
                    
                }
            });
            telaExcluir.addWindowListener(new WindowAdapter(){
                
                @Override
                public void windowClosed(WindowEvent e){
                    try{
                        String opcao_Crescente_Decrescente = (jComboBox_Ordenacao1.getSelectedItem().toString().contains("Crescente"))? "Crescente":"Decrescente";
                        List<Aluno> listaAuxiliar = telaExcluir.getList(opcao_Crescente_Decrescente);
                        arvore = new ArvoreBinaria(ordenacao_Nome_Matricula, jComboBox_Ordenacao2.getSelectedItem().toString());
                        if(arvore != null){
                            for(Aluno aluno : listaAuxiliar){
                                arvore.incluir(aluno);
                            }
                            mostrarNaGrid(opcao_Crescente_Decrescente);
                        }
                    } catch(Exception erro){
                        JOptionPane.showMessageDialog(e.getWindow(), "Erro ao Excluir: " + erro.getMessage());
                    }
                }
            });
            
        } catch (Exception erro) {
            JOptionPane.showMessageDialog(this, "Erro ao Buscar: " + erro.getMessage());
        }
    }//GEN-LAST:event_jButton_ExcluirActionPerformed

